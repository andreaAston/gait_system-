-- Complete Supabase setup for the GAIT Monitoring Dashboard.
-- Run once on a new, empty database, then run seed_demo_data.sql.

BEGIN;

CREATE TABLE IF NOT EXISTS public.patients (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  full_name text NOT NULL,
  date_of_birth date,
  gender text CHECK (
    gender IS NULL
    OR gender IN ('female', 'male', 'other', 'prefer_not_to_say')
  ),
  status text NOT NULL DEFAULT 'inactive'
    CHECK (status IN ('active', 'inactive', 'discharged')),
  notes text,
  registered_at timestamptz NOT NULL DEFAULT now(),
  registered_by uuid REFERENCES auth.users(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS public.devices (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  device_code text NOT NULL UNIQUE,
  label text,
  registered_at timestamptz NOT NULL DEFAULT now(),
  last_seen_at timestamptz
);

ALTER TABLE public.devices
  ADD COLUMN IF NOT EXISTS last_seen_at timestamptz;

CREATE TABLE IF NOT EXISTS public.device_assignments (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  device_id uuid NOT NULL REFERENCES public.devices(id) ON DELETE CASCADE,
  patient_id uuid NOT NULL REFERENCES public.patients(id) ON DELETE CASCADE,
  started_at timestamptz NOT NULL DEFAULT now(),
  ended_at timestamptz,
  ended_reason text,
  CHECK (ended_at IS NULL OR ended_at >= started_at)
);

CREATE UNIQUE INDEX IF NOT EXISTS device_assignments_one_active_device
  ON public.device_assignments (device_id)
  WHERE ended_at IS NULL;

CREATE UNIQUE INDEX IF NOT EXISTS device_assignments_one_active_patient
  ON public.device_assignments (patient_id)
  WHERE ended_at IS NULL;

CREATE INDEX IF NOT EXISTS device_assignments_patient_started
  ON public.device_assignments (patient_id, started_at DESC);

CREATE TABLE IF NOT EXISTS public.sensors (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  subsystem text NOT NULL,
  sensor_type text NOT NULL,
  label text NOT NULL,
  unit text NOT NULL,
  UNIQUE (subsystem, sensor_type, label),
  CHECK (
    subsystem IN ('foot_left', 'foot_right', 'crutch_left', 'crutch_right')
  )
);

CREATE TABLE IF NOT EXISTS public.gait_readings (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  device_id uuid NOT NULL REFERENCES public.devices(id) ON DELETE CASCADE,
  recorded_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS gait_readings_device_recorded
  ON public.gait_readings (device_id, recorded_at DESC);

CREATE TABLE IF NOT EXISTS public.reading_values (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reading_id bigint NOT NULL REFERENCES public.gait_readings(id) ON DELETE CASCADE,
  sensor_id uuid NOT NULL REFERENCES public.sensors(id) ON DELETE RESTRICT,
  value double precision NOT NULL,
  is_simulated boolean NOT NULL DEFAULT false,
  UNIQUE (reading_id, sensor_id)
);

ALTER TABLE public.reading_values
  ADD COLUMN IF NOT EXISTS is_simulated boolean NOT NULL DEFAULT false;

CREATE INDEX IF NOT EXISTS reading_values_sensor_reading
  ON public.reading_values (sensor_id, reading_id);

ALTER TABLE public.patients ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.devices ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.device_assignments ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sensors ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.gait_readings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.reading_values ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS authenticated_users_manage_patients ON public.patients;
CREATE POLICY authenticated_users_manage_patients ON public.patients
  FOR ALL TO authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS authenticated_users_manage_devices ON public.devices;
CREATE POLICY authenticated_users_manage_devices ON public.devices
  FOR ALL TO authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS authenticated_users_manage_assignments ON public.device_assignments;
CREATE POLICY authenticated_users_manage_assignments ON public.device_assignments
  FOR ALL TO authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS authenticated_users_manage_sensors ON public.sensors;
CREATE POLICY authenticated_users_manage_sensors ON public.sensors
  FOR ALL TO authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS authenticated_users_manage_gait_readings ON public.gait_readings;
CREATE POLICY authenticated_users_manage_gait_readings ON public.gait_readings
  FOR ALL TO authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS authenticated_users_manage_reading_values ON public.reading_values;
CREATE POLICY authenticated_users_manage_reading_values ON public.reading_values
  FOR ALL TO authenticated USING (true) WITH CHECK (true);

GRANT USAGE ON SCHEMA public TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE
  ON public.patients, public.devices, public.device_assignments,
     public.sensors, public.gait_readings, public.reading_values
  TO authenticated;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO authenticated;

CREATE OR REPLACE FUNCTION public.recalculate_patient_status(patient_id_to_sync uuid)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
BEGIN
  UPDATE public.patients AS patient
  SET status = CASE
    WHEN EXISTS (
      SELECT 1
      FROM public.device_assignments AS assignment
      WHERE assignment.patient_id = patient.id
        AND assignment.ended_at IS NULL
    ) THEN 'active'
    WHEN EXISTS (
      SELECT 1
      FROM public.device_assignments AS assignment
      WHERE assignment.patient_id = patient.id
    ) THEN 'discharged'
    ELSE 'inactive'
  END
  WHERE patient.id = patient_id_to_sync;
END;
$$;

CREATE OR REPLACE FUNCTION public.sync_patient_status_after_assignment()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    PERFORM public.recalculate_patient_status(NEW.patient_id);
    RETURN NEW;
  END IF;

  IF TG_OP = 'DELETE' THEN
    PERFORM public.recalculate_patient_status(OLD.patient_id);
    RETURN OLD;
  END IF;

  PERFORM public.recalculate_patient_status(OLD.patient_id);
  IF NEW.patient_id IS DISTINCT FROM OLD.patient_id THEN
    PERFORM public.recalculate_patient_status(NEW.patient_id);
  END IF;
  RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION public.recalculate_patient_status(uuid)
  FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.sync_patient_status_after_assignment()
  FROM PUBLIC, anon, authenticated;

DROP TRIGGER IF EXISTS device_assignments_sync_patient_status
  ON public.device_assignments;

CREATE TRIGGER device_assignments_sync_patient_status
AFTER INSERT OR UPDATE OR DELETE ON public.device_assignments
FOR EACH ROW
EXECUTE FUNCTION public.sync_patient_status_after_assignment();

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_publication WHERE pubname = 'supabase_realtime'
  ) THEN
    RAISE EXCEPTION 'Supabase Realtime publication "supabase_realtime" was not found.';
  END IF;

  IF NOT EXISTS (
    SELECT 1
    FROM pg_publication_tables
    WHERE pubname = 'supabase_realtime'
      AND schemaname = 'public'
      AND tablename = 'reading_values'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.reading_values;
  END IF;
END;
$$;

COMMIT;
